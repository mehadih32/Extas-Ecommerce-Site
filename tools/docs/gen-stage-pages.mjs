/** Rows of the first table after the heading that starts with `prefix`. */
function tableAfter(md, prefix) {
  const lines = md.split('\n');
  const start = lines.findIndex((l) => l.startsWith(prefix));
  if (start < 0) return [];
  const rows = [];
  let inTable = false;
  for (let i = start + 1; i < lines.length; i++) {
    const line = lines[i];
    if (line.startsWith('|')) {
      inTable = true;
      const cs = cells(line);
      if (!isSeparator(cs)) rows.push(cs);
    } else if (inTable) break;
    else if (/^#{1,3}\s/.test(line)) break;
  }
  return rows.slice(1);
}

