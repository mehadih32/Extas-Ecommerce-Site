/** "(1) … (2) …" → [{ label, start, end }] for one level of enumeration. */
function enumSegments(text, re) {
  const hits = [...text.matchAll(re)];
  return hits.map((m, i) => ({ label: m[1], start: m.index, end: i + 1 < hits.length ? hits[i + 1].index : text.length }));
}

