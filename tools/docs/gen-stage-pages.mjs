// README: link stage names, waves and PR numbers -------------------------------------------------------
function linkNumbers(text, mode) {
  // mode "list": every number/range is a PR ("1–10, 601, 604"); mode "prose": only numbers after "PR ".
  const one = (a, b) => {
    const sa = stageOf.get(a);
    if (!sa) return null;
    if (b == null) return `[${a}](docs/stages/${sa}.md#pr-${a})`;
    const sb = stageOf.get(b);
    return `[${a}–${b}](docs/stages/${sa === sb ? `${sa}.md` : 'README.md'})`;
  };
  if (mode === 'list') {
    return text.replace(NUM_RE, (all, a, b) => one(Number(a), b ? Number(b) : null) ?? all);
  }
  return text.replace(/\bPR\s+(\d{1,3})(?:\s*[–-]\s*(\d{1,3}))?(?![\w:])/g, (all, a, b) => {
    const l = one(Number(a), b ? Number(b) : null);
    return l ? `PR ${l}` : all;
  });
}

function relinkReadme(md) {
  // Only the rows rewritten below lose their old docs/stages links first; every other line stays as written.
  const lines = md.split('\n');
  const row = (cs) => `| ${cs.join(' | ')} |`;
  let section = '';
  let header = null;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (/^#{2,3}\s/.test(line)) {
      section = line.replace(/^#+\s*/, '');
      header = null;
      continue;
    }
    if (!line.startsWith('|')) {
      header = null;
      continue;
    }
    const cs = cells(unlink(line));
    if (!header) {
      header = cs;
      continue;
    }
    if (isSeparator(cs)) continue;
    if (section === 'Status dashboard' && header[0] === 'Item') {
      if (/^stages$/i.test(plainMd(cs[0]))) continue; // kept identical to the register's progress line
      cs[1] = linkNumbers(cs[1], 'prose');
      lines[i] = row(cs);
    } else if (section === 'All 28 stages' && header[0] === 'Stage') {
      const id = cs[0];
      if (!stageById.has(id)) continue;
      cs[0] = `[${id}](docs/stages/${id}.md)`;
      cs[1] = `[${cs[1]}](docs/stages/${id}.md)`;
      const w = cs[2].trim();
      if (/^\d+$/.test(w)) cs[2] = `[${w}](docs/stages/README.md#wave-${w})`;
      else if (w === '—') cs[2] = '[—](docs/stages/README.md#parked)';
      cs[3] = linkNumbers(cs[3], 'list');
      lines[i] = row(cs);
    } else if (section === 'PR log' && header[0] === 'GitHub') {
      if (/^PR \d/.test(cs[1])) cs[1] = `PR ${linkNumbers(cs[1].slice(3), 'list')}`;
      cs[3] = linkNumbers(cs[3], 'prose');
      lines[i] = row(cs);
    }
  }
  return lines.join('\n');
}

