/**
 * A date in register prose: "19 Oct 23:33", "20 Oct 2026", "Owner 22:14" (day from `fallbackDay`). With no time of its
 * own, an entry on the same day as `fallbackDay` takes `fallbackMin` (it was written after that entry); otherwise it
 * sorts at the start of its day. An entry with no day sorts at the very end.
 */
function parseDate(text, fallbackDay = null, fallbackMin = null) {
  const d = text.match(/\b(\d{1,2}) Oct\b/);
  const t = text.match(/\b(\d{1,2}):(\d{2})\b/);
  const day = d ? Number(d[1]) : fallbackDay;
  let min = t ? Number(t[1]) * 60 + Number(t[2]) : null;
  if (min == null && day != null && day === fallbackDay) min = fallbackMin;
  const label = day == null ? '' : `${day} Oct${t ? ` ${t[1].padStart(2, '0')}:${t[2]}` : ''}`;
  const key = day == null ? Number.MAX_SAFE_INTEGER : day * 1440 + (min ?? 0);
  return { day, min, label, key };
}

/** Shorten long prose for a page, keeping the markdown balanced. */
function excerpt(text, max = 600) {
  let s = text.trim();
  if (s.length <= max) return s;
  s = s.slice(0, max);
  s = s.slice(0, Math.max(s.lastIndexOf(' '), max * 0.6)).replace(/[\s,;:(—–-]+$/, '');
  for (const mark of ['**', '~~', '`']) {
    const count = s.split(mark).length - 1;
    if (count % 2) s += mark;
  }
  return `${s} …`;
}

