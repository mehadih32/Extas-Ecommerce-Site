/** Split a register cell into its original text and its dated "Updated …"-style additions. */
export function splitMarkers(text, fallback = { day: null, min: null }) {
  const marks = [];
  let lastDay = fallback.day;
  let lastMin = fallback.min;
  for (const m of text.matchAll(/\*\*([^*]+?)\*\*(:?)/g)) {
    const content = m[1].trim();
    const here = parseDate(content, lastDay, lastMin);
    const dated = /\b\d{1,2} Oct\b|\b\d{1,2}:\d{2}\b/.test(content);
    const lead = /^(Updated|V2\.1 final)\b/.test(content);
    const colon = /:$/.test(content) || m[2] === ':';
    if (lead || (m.index > 0 && colon && dated)) marks.push({ index: m.index, content, date: here });
    if (dated && here.day != null) {
      lastDay = here.day;
      lastMin = here.min;
    }
  }
  const original = (marks.length ? text.slice(0, marks[0].index) : text).trim();
  const updates = marks.map((mk, i) => ({
    date: mk.date,
    text: text.slice(mk.index, i + 1 < marks.length ? marks[i + 1].index : text.length).trim(),
  }));
  return { original, updates };
}

