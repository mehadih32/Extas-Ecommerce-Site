/** Markdown → plain text, the way GitHub reads a heading for its anchor. */
const plainMd = (s) =>
  s
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\*\*|__|`|~~/g, '')
    .replace(/(^|\s)\*(\S[^*]*)\*/g, '$1$2')
    .trim();

/** GitHub heading anchor (lowercase, punctuation dropped, spaces → hyphens). */
export const slugify = (text) =>
  plainMd(text)
    .toLowerCase()
    .replace(/<[^>]+>/g, '')
    .replace(/[^\p{L}\p{M}\p{N}\p{Pc}\- ]/gu, '')
    .replace(/ /g, '-');

/** Every heading of a markdown file with its GitHub anchor (duplicates get -1, -2 …). */
export function headings(md) {
  const seen = new Map();
  const out = [];
  let fence = false;
  md.split('\n').forEach((line, i) => {
    if (/^```/.test(line)) fence = !fence;
    const m = !fence && line.match(/^(#{1,6})\s+(.+?)\s*#*\s*$/);
    if (!m) return;
    const base = slugify(m[2]);
    const n = seen.get(base) ?? 0;
    seen.set(base, n + 1);
    out.push({ level: m[1].length, text: m[2], plain: plainMd(m[2]), anchor: n ? `${base}-${n}` : base, line: i });
  });
  return out;
}

/** Cells of a markdown table row (a row may lack its closing pipe). */
const cells = (line) => {
  let s = line.trim();
  if (s.startsWith('|')) s = s.slice(1);
  if (s.endsWith('|')) s = s.slice(0, -1);
  return s.split('|').map((c) => c.trim());
};
const isSeparator = (cs) => cs.every((c) => /^:?-+:?$/.test(c));
const cellText = (s) => s.replace(/\|/g, '\\|');

/** "1–10, 601, 604" → [1..10, 601, 604] in the order written. */
export function expandRange(text) {
  const out = [];
  for (const tok of text.split(',')) {
    const m = tok.trim().match(/^(\d+)(?:\s*[–-]\s*(\d+))?$/);
    if (!m) continue;
    const a = Number(m[1]);
    const b = m[2] ? Number(m[2]) : a;
    for (let n = a; n <= b; n++) out.push(n);
  }
  return out;
}

/** PR numbers referred to in prose: "PR 4/17", "PR 1, 3–10, 13", "PR 148, 292 and 545", "PRs 571–576". */
export function prRefs(text) {
  const out = [];
  const re = /\bPRs?\s+(\d+(?:\s*[–-]\s*\d+)?(?:\s*(?:,|\/|\band\b|&|\+)\s*\d+(?:\s*[–-]\s*\d+)?)*)/g;
  for (const m of plainMd(text).matchAll(re)) {
    for (const part of m[1].split(/\s*(?:,|\/|\band\b|&|\+)\s*/)) {
      const r = part.match(/^(\d+)(?:\s*[–-]\s*(\d+))?$/);
      if (!r) continue;
      const a = Number(r[1]);
      const b = r[2] ? Number(r[2]) : a;
      if (b - a > 100) continue;
      for (let n = a; n <= b; n++) if (n >= 1 && n <= MAX_PR && !out.includes(n)) out.push(n);
    }
  }
  return out;
}

