// S21 · PR 570 (B7.3, Note 14/21) — the e-commerce checklist in the backend. docs/qa/ECOMMERCE-CHECKLIST.md (the QA
// master, edited by hand) is read into docs/qa/audit-checklist.json: its groups (the numbered sections, and the timing
// points L32/L33 added on 19 Oct), each point's id, words and its newest QA mark. The admin's Checklist audit page
// (AI section) shows it; the server's audit runner (infra/deploy/audit.sh, tools/audit-report.mjs) reports on the
// groups the owner chose. The same JSON is written for the app (APP_OUT). A test fails when either is older than the
// checklist (run this again after editing it).
//   node tools/audit-checklist.mjs            (writes docs/qa/audit-checklist.json)
//   node tools/audit-checklist.mjs --check    (exit 1 when the JSON is out of date)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const CHECKLIST = 'docs/qa/ECOMMERCE-CHECKLIST.md';
export const OUT = 'docs/qa/audit-checklist.json';
/** The admin's copy (the app's build reads only its own folder). */
export const APP_OUT = 'apps/web/src/lib/admin-health/audit-checklist.json';

/** The marks, in the words the JSON keeps. */
const MARKS = [
  ['✅', 'pass'],
  ['❌', 'fail'],
  ['🔒', 'ownerData'],
  ['⚖', 'decision'],
  ['⬜', 'notRun'],
  ['—', 'notTestable'],
];
export const MARK_KEYS = MARKS.map(([, k]) => k);
const TEXT_MAX = 180;

/** The newest mark of one line: the last round's bold mark when there is one ("R15b ❌ → R15 wave 2 ✅" ends ✅). */
export function markOf(line) {
  const rounds = [...line.matchAll(/\*\*(R\d+[a-z]?[^*]*)\*\*/g)].map((m) => m[1]);
  const last = rounds.length ? rounds[rounds.length - 1] : line;
  let best = null;
  let at = -1;
  for (const [sym, key] of MARKS) {
    const i = last.lastIndexOf(sym);
    if (i > at) {
      at = i;
      best = key;
    }
  }
  return best ?? 'notRun';
}

/** A point's words without its marks and notes: what it checks, cut to a readable length. */
function wordsOf(s) {
  let t = s.split(' *(')[0];
  // the marks and rounds in front ("✅ · **R15b ❌ → R15 wave 2 ✅** · …"), then a "(bug 1 fixed — …)" note
  t = t.replace(/^(?:\s*(?:[✅❌🔒⚖⬜—]|\*\*[^*]*\*\*)\s*·?)+/u, '').trim();
  t = t.replace(/^\((?:[^()]|\([^()]*\))*\)\s*/, '');
  t = t
    .replace(/\*\*[^*]*(?:TA-\d|R\d+[a-z]?)[^*]*\*\*/g, '')
    .replace(/\*\*/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  return t.length > TEXT_MAX ? `${t.slice(0, TEXT_MAX - 1)}…` : t;
}

/** The checklist's groups and points. */
export function parseChecklist(md) {
  const groups = [];
  let g = null;
  for (const line of md.split('\n')) {
    const h = /^## (\d+)\. (.+)$/.exec(line);
    if (h) {
      g = { id: h[1], title: h[2].trim(), points: [] };
      groups.push(g);
      continue;
    }
    if (/^## Added .*owner catch/.test(line)) {
      g = { id: 'timing', title: 'Pauses and resumes (L32, L33)', points: [] };
      groups.push(g);
      continue;
    }
    if (/^## /.test(line)) {
      g = null;
      continue;
    }
    if (!g) continue;
    const p = /^- \[([A-Z]+\d+[a-z]?)\]\s*(.*)$/.exec(line);
    if (p) {
      g.points.push({ id: p[1], text: wordsOf(p[2]), mark: markOf(p[2]) });
      continue;
    }
    const row = /^\| (L\d+(?:\.\d+)?) \| (.+?) \| (.+?) \|$/.exec(line);
    if (row) g.points.push({ id: row[1], text: wordsOf(row[2]), mark: markOf(row[2]), where: row[3].trim() });
  }
  return groups.filter((x) => x.points.length);
}

/** The JSON the admin and the runner read. */
export function checklistJson(md) {
  const groups = parseChecklist(md);
  const counts = (pts) => Object.fromEntries(MARK_KEYS.map((k) => [k, pts.filter((p) => p.mark === k).length]));
  return {
    $comment: `Generated by tools/audit-checklist.mjs from ${CHECKLIST}; do not edit by hand.`,
    source: CHECKLIST,
    points: groups.reduce((n, x) => n + x.points.length, 0),
    groups: groups.map((x) => ({ ...x, counts: counts(x.points) })),
  };
}

export const render = (md) => `${JSON.stringify(checklistJson(md), null, 1)}\n`;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const want = render(readFileSync(join(root, CHECKLIST), 'utf8'));
  if (process.argv.includes('--check')) {
    for (const f of [OUT, APP_OUT]) {
      let have = '';
      try {
        have = readFileSync(join(root, f), 'utf8');
      } catch {}
      if (have !== want) {
        console.error(`${f} is out of date: run node tools/audit-checklist.mjs`);
        process.exit(1);
      }
    }
    console.log('the checklist JSON is up to date');
  } else {
    for (const f of [OUT, APP_OUT]) writeFileSync(join(root, f), want);
    console.log(`wrote ${OUT} and ${APP_OUT}`);
  }
}
